const TRANSLATIONS = Object.freeze({
  en: ENGLISH,
  "zh-CN": ZH_CN,
  ru: RUSSIAN,
  fa: PERSIAN
});

const TRANSLATION_KEYS = Object.freeze(Object.keys(ENGLISH));

function getLocaleCatalog(locale) {
  return TRANSLATIONS[resolveLocale(locale)];
}

export function hasTranslation(locale, key) {
  return typeof key === "string" && Object.prototype.hasOwnProperty.call(getLocaleCatalog(locale), key);
}

export function translate(locale, key, fallbackLocale = DEFAULT_LOCALE) {
  if (typeof key !== "string" || key.length === 0) return "";
  const resolved = resolveLocale(locale);
  const fallback = resolveLocale(fallbackLocale);
  return TRANSLATIONS[resolved][key] ?? TRANSLATIONS[fallback][key] ?? key;
}

export function createTranslator(locale, fallbackLocale = DEFAULT_LOCALE) {
  const resolved = resolveLocale(locale);
  const fallback = resolveLocale(fallbackLocale);
  return Object.freeze({
    locale: resolved,
    direction: resolved === "fa" ? "rtl" : "ltr",
    t: (key) => translate(resolved, key, fallback)
  });
}

export {
  TRANSLATIONS,
  TRANSLATION_KEYS,
  getLocaleCatalog,
  SUPPORTED_LOCALES
};
